using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using SptApi.Common;
using SptApi.Dtos.Requests;
using SptApi.Services;

namespace SptApi.Controllers;

// Admin "People" pages and the audit log (route prefix kept as /api/auth/admin for the frontend).
[Route("api/auth/admin")]
[Authorize(Roles = Roles.Admin)]
public class AdminController(
    ITeacherService teachers,
    IStudentService students,
    IUserAccountService accounts,
    IAuditLogService auditLogs) : ApiControllerBase
{
    // ───────── Teachers ─────────

    // GET /api/auth/admin/teachers
    [HttpGet("teachers")]
    public async Task<IActionResult> GetTeachers() =>
        Respond(await teachers.GetAllAsync());

    // POST /api/auth/admin/create-teacher   (employee ID is generated by the server)
    [HttpPost("create-teacher")]
    public async Task<IActionResult> CreateTeacher([FromBody] AdminCreateTeacherRequest request) =>
        Respond(await teachers.CreateAsync(request));

    // PATCH /api/auth/admin/teachers/{id}   { subjects: [ids] }
    [HttpPatch("teachers/{id:int}")]
    public async Task<IActionResult> UpdateTeacherSubjects(int id, [FromBody] UpdateTeacherSubjectsRequest request) =>
        Respond(await teachers.UpdateSubjectsAsync(id, request));

    // ───────── Students ─────────

    // GET /api/auth/admin/students
    [HttpGet("students")]
    public async Task<IActionResult> GetStudents() =>
        Respond(await students.GetAllAsync());

    // POST /api/auth/admin/create-student   (student ID number is generated by the server)
    [HttpPost("create-student")]
    public async Task<IActionResult> CreateStudent([FromBody] AdminCreateStudentRequest request) =>
        Respond(await students.CreateAsync(request));

    // DELETE /api/auth/admin/students/{id}   (only an unregistered, pre-loaded student ID)
    [HttpDelete("students/{id:int}")]
    public async Task<IActionResult> RemoveStudentRecord(int id) =>
        Respond(await students.RemoveUnregisteredAsync(id));

    // ───────── Any user ─────────

    // PATCH /api/auth/admin/users/{userId}
    [HttpPatch("users/{userId:int}")]
    public async Task<IActionResult> UpdateUser(int userId, [FromBody] AdminUpdateUserRequest request) =>
        Respond(await accounts.UpdateAsync(userId, request));

    // DELETE /api/auth/admin/users/{userId}   (soft delete: the account is deactivated, nothing is removed)
    [HttpDelete("users/{userId:int}")]
    public async Task<IActionResult> DeleteUser(int userId) =>
        Respond(await accounts.SoftDeleteAsync(userId));

    // ───────── Audit log ─────────

    // GET /api/auth/admin/audit-logs?action=&actor_type=&actor_id=&email=
    [HttpGet("audit-logs")]
    public async Task<IActionResult> GetAuditLogs(
        [FromQuery] string? action, [FromQuery(Name = "actor_type")] string? actorType,
        [FromQuery(Name = "actor_id")] string? actorId, [FromQuery] string? email) =>
        Respond(await auditLogs.SearchAsync(action, actorType, actorId, email));
}
