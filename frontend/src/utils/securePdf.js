import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

// Grade exports are PDF only (no CSV/Excel) so nobody can open the file and change a grade.
// The PDF is also locked with permissions: anyone can open and print it, but PDF readers block
// editing, copying and form changes. The owner password is random and never shown, so the lock
// can't be lifted from inside the app.
function randomOwnerPassword() {
  const bytes = new Uint8Array(24);
  window.crypto.getRandomValues(bytes);
  return Array.from(bytes, (b) => b.toString(16).padStart(2, '0')).join('');
}

// title, subtitleLines: text above the table. head: column names. body: rows of cell text.
export function downloadLockedGradePdf({ fileName, title, subtitleLines = [], head, body }) {
  const doc = new jsPDF({
    orientation: 'landscape',
    encryption: {
      userPassword: '',                 // opens without a password
      ownerPassword: randomOwnerPassword(),
      userPermissions: ['print'],       // print only: no modify / copy / annotate
    },
  });

  doc.setFontSize(15);
  doc.text(title, 14, 16);
  doc.setFontSize(10);
  const lines = [...subtitleLines, `Generated: ${new Date().toLocaleString()}`];
  lines.forEach((line, i) => doc.text(line, 14, 23 + i * 6));

  autoTable(doc, {
    startY: 23 + lines.length * 6 + 2,
    head: [head],
    body,
    styles: { fontSize: 9, cellPadding: 2.4 },
    headStyles: { fillColor: [30, 35, 53] },
    alternateRowStyles: { fillColor: [245, 247, 250] },
    didDrawPage: () => {
      const { height, width } = doc.internal.pageSize;
      doc.setFontSize(8);
      doc.text('Official copy generated by the Student Performance Tracker. Editing is disabled.', 14, height - 8);
      doc.text(`Page ${doc.getNumberOfPages()}`, width - 30, height - 8);
    },
  });

  doc.save(fileName);
}
